import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from appasm import Asm, make_app
# Passive Wi-Fi scanner: CENTER scans (about 2 s, receive only), then lists RSSI, channel and SSID.
a = Asm()
for v in ('k', 'n', 'i', 'y'): a.var(v)
BLACK, WHITE, GREEN, RED, CYAN, AMBER, GRAY, BLUE = range(8)
a.label('start')
a.op('CLS')
a.text(0, 0, WHITE, 'PASSIVE WI-FI SCAN')
a.text(0, 12, GRAY, 'CENTER = SCAN  HOLD = EXIT')
a.label('wait')
a.e(30); a.op('FRAME')
a.set('k', 'key')
a.e('k', 5, '=='); a.jz('wait')
a.rect(0, 24, 240, 232, BLACK)
a.text(0, 24, AMBER, 'SCANNING...')
a.sys(20); a.st('n')
a.rect(0, 24, 240, 232, BLACK)
a.e('n', 0, '<'); a.jz('ok')
a.text(0, 24, RED, 'SCAN FAILED')
a.jmp('wait')
a.label('ok')
a.e('n', 0, '=='); a.jz('list')
a.text(0, 24, GRAY, 'NO NETWORKS HEARD')
a.jmp('wait')
a.label('list')
a.text(0, 24, CYAN, 'RSSI CH SSID')
a.set('i', 0)
a.label('row')
a.e('i', 'n', '>='); a.jnz('wait')
a.e('i', 12, '>='); a.jnz('wait')
a.set('y', 38, 'i', 16, '*', '+')
a.e(0, 'y'); a.sys(21, 'i'); a.e(CYAN); a.op('NUM')
a.e(40, 'y'); a.sys(22, 'i'); a.e(AMBER); a.op('NUM')
a.sys(26, 'i', 70, 'y'); a.op('DROP')
a.set('i', 'i', 1, '+')
a.jmp('row')
code = a.finish()
open(os.path.join(os.path.dirname(__file__), '..', 'sdcard_examples', 'APPS', 'WIFISCAN.APP'), 'w', newline='\n').write(
    make_app('WIFISCAN', 'Utilities', '1.0', 'Passive Wi-Fi scanner using the SYS device calls', code))
print('WIFISCAN.APP', len(code), 'bytes of code')
