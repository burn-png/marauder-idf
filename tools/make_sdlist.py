import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from appasm import Asm, make_app
# SD card lister: UP/DOWN select, CENTER previews the first bytes of a file, hold CENTER exits.
a = Asm()
for v in ('n', 'i', 'k', 'sel', 'y', 'got', 'j', 'isd'): a.var(v)
a.var('nm', 4); a.var('name', 48); a.var('buf', 64)
BLACK, WHITE, GREEN, RED, CYAN, AMBER, GRAY, BLUE = range(8)
ad = lambda v: a.vars[v][0]                           # address of a variable (for calls that take a memory address)
a.str('nm', '')
a.label('start')
a.op('CLS')
a.text(0, 0, WHITE, 'SD CARD (ROOT)')
a.sys(37, ad('nm')); a.st('n')
a.e('n', 0, '<'); a.jz('have')
a.text(0, 14, RED, 'CANNOT READ CARD'); a.jmp('idle')
a.label('have')
a.set('sel', 0)
a.label('redraw')
a.rect(0, 12, 240, 244, BLACK)
a.sys(29, WHITE); a.op('DROP')
a.set('i', 0)
a.label('row')
a.e('i', 'n', '>='); a.jnz('rows_done')
a.set('y', 14, 'i', 12, '*', '+')
a.e('i', 'sel', '=='); a.jz('plain')
a.rect(0, 'y', 240, 11, BLUE)
a.label('plain')
a.sys(38, 'i', ad('name')); a.op('DROP')
a.sys(39, 'i'); a.st('isd')
a.e('isd', 1, '=='); a.jz('file_color')
a.sys(29, CYAN); a.op('DROP'); a.jmp('draw_name')
a.label('file_color')
a.sys(29, WHITE); a.op('DROP')
a.label('draw_name')
a.sys(27, ad('name'), 4, 'y'); a.op('DROP')
a.set('i', 'i', 1, '+'); a.jmp('row')
a.label('rows_done')
a.label('idle')
a.e(40); a.op('FRAME')
a.set('k', 'key')
a.e('k', 0, '=='); a.jnz('idle')
a.e('k', 1, '=='); a.jz('not_up')
a.set('sel', 'sel', 1, '-'); a.e('sel', 0, '<'); a.jz('redraw'); a.set('sel', 'n', 1, '-'); a.jmp('redraw')
a.label('not_up')
a.e('k', 2, '=='); a.jz('not_down')
a.set('sel', 'sel', 1, '+'); a.e('sel', 'n', '>='); a.jz('redraw'); a.set('sel', 0); a.jmp('redraw')
a.label('not_down')
a.e('k', 5, '=='); a.jz('idle')
# preview: open the selected file, show its first 40 bytes on the bottom line
a.sys(39, 'sel'); a.jnz('idle')                       # folders: nothing to preview
a.sys(38, 'sel', ad('name')); a.op('DROP')
a.sys(30, ad('name'), 0); a.jz('idle')
a.sys(33, ad('buf'), 40); a.st('got')
a.sys(36); a.op('DROP')
a.set('j', 0)
a.label('clean')                                      # printable ASCII only, 0 terminated
a.e('j', 'got', '>='); a.jnz('term')
a.e('j', '@buf', 32, '<'); a.jz('keep_ch'); a.sta('buf', [46], ['j'])
a.label('keep_ch')
a.set('j', 'j', 1, '+'); a.jmp('clean')
a.label('term')
a.sta('buf', [0], ['got'])
a.rect(0, 244, 240, 11, BLACK)
a.sys(29, AMBER); a.op('DROP')
a.sys(27, ad('buf'), 4, 244); a.op('DROP')
a.jmp('idle')
code = a.finish()
open(os.path.join(os.path.dirname(__file__), '..', 'sdcard_examples', 'APPS', 'SDLIST.APP'), 'w', newline='\n').write(
    make_app('SDLIST', 'Utilities', '1.0', 'Lists the SD root and previews files, using the file SYS calls', code))
print('SDLIST.APP', len(code), 'bytes of code')
